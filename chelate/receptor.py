"""
Description
-----------
Metal-site extraction from receptor structures.

Two ways in, depending on what you have: :func:`extract_metals` reads an already-parsed
RDKit molecule, :func:`extract_metal_symbols_from_pdb` scans PDB text directly and is
tolerant of files RDKit refuses to sanitise.

The symbols returned here decide which ``has_{Metal}`` columns are set for a system —
see :func:`chelate.schema.metal_one_hot`.
"""

import hashlib
import json
import os
import re
import warnings
from collections import Counter
from functools import cache
from pathlib import Path

import numpy as np
from rdkit import Chem

from chelate.constants import METAL_ATOMS_SET, METAL_ELEMENT_SYMBOLS


def extract_metals(mol: Chem.rdchem.Mol) -> list[tuple[str, np.ndarray]]:
    """
    Extract metal atoms and their coordinates from an RDKit molecule.
    Only atoms whose element is in ``METAL_ELEMENT_SYMBOLS`` are returned.

    Parameters
    ----------
    mol : Chem.rdchem.Mol
        Molecule (typically a parsed receptor PDB) with a conformer.

    Returns
    -------
    list[tuple[str, np.ndarray]]
        List of (element_symbol, xyz_array) pairs for each metal atom found.
    """
    conf: Chem.Conformer = mol.GetConformer()
    metals: list[tuple[str, np.ndarray]] = []
    for atom in mol.GetAtoms():
        symbol: str = atom.GetSymbol().capitalize()
        if symbol not in METAL_ELEMENT_SYMBOLS:
            continue
        pos: Chem.RPoint3D = conf.GetAtomPosition(atom.GetIdx())
        metals.append((symbol, np.asarray([pos.x, pos.y, pos.z], dtype=np.float32)))
    return metals


def extract_metal_symbols_from_pdb(pdb_path: str) -> set[str]:
    """
    Extract metal element symbols from PDB text records (ATOM/HETATM).

    Checks the standard PDB element field (columns 77-78) first. Only when that field
    is blank does it fall back to the record's names, and then only for HETATM
    single-atom ion records whose residue name equals the atom name (e.g. ``ZN ZN``).
    This avoids misreading atom names such as ``CA`` in selenomethionine or ``NA`` in
    haem as metals.

    Parameters
    ----------
    pdb_path : str
        Path to the PDB file.

    Returns
    -------
    set of str
        Upper-case metal element symbols found in the file (e.g. ``{'ZN', 'FE'}``).
        Returns an empty set if the file does not exist.
    """
    metals = set()

    if not os.path.exists(pdb_path):
        return metals

    with open(pdb_path) as fh:
        for line in fh:
            if not line.startswith(("ATOM", "HETATM")):
                continue

            record = line[0:6].strip()
            atom_name = line[12:16].strip().upper() if len(line) >= 16 else ""
            res_name = line[17:20].strip().upper() if len(line) >= 20 else ""

            # PDB element field is columns 77-78 (1-based indexing).
            element = line[76:78].strip().upper() if len(line) >= 78 else ""
            if element:
                if element in METAL_ATOMS_SET:
                    metals.add(element)
                continue

            # Fallback for a missing element field: only trust single-atom ion
            # records (residue name == atom name), never protein or ligand atom names.
            if record == "HETATM":
                clean_res = re.sub(r"[^A-Z]", "", res_name)
                clean_atom = re.sub(r"[^A-Z]", "", atom_name)
                if clean_res == clean_atom and clean_res in METAL_ATOMS_SET:
                    metals.add(clean_res)

    return metals


def load_receptor_pdb(path: str | Path) -> Chem.rdchem.Mol | None:
    """Read a prepared receptor without adding bonds to a complete CONECT graph.

    OpenBabel's PDBQT conversion already writes explicit connectivity. RDKit's
    default proximity bonding can add spurious bonds between nearby restored
    atoms, including terminal oxygens and arginine nitrogens, making an otherwise
    valid prepared receptor fail sanitisation. Complete explicit connectivity is
    authoritative. PDBs without it keep RDKit's normal bond perception.
    A PDBQT conversion by OpenBabel (its header, or a source-validated
    sidecar) also has authoritative connectivity when some atoms are isolated.
    Failed standard residues can have incorrect bond orders restored from RDKit
    templates. Atom records, coordinates, metals and formal charges are never
    changed.
    """
    path = Path(path)
    atoms = []
    connected = set()
    has_connectivity = False
    openbabel_output = False
    for line in path.read_text().splitlines():
        if line.startswith("AUTHOR") and "GENERATED BY OPEN BABEL" in line:
            openbabel_output = True
        elif line.startswith(("ATOM", "HETATM")):
            element = line[76:78].strip().capitalize()
            if element in {"H", "D"} or element in METAL_ELEMENT_SYMBOLS:
                continue
            atoms.append((int(line[6:11]), line[17:27]))
        elif line.startswith("CONECT"):
            serials = [
                int(line[start : start + 5])
                for start in range(6, len(line), 5)
                if line[start : start + 5].strip()
            ]
            if len(serials) > 1:
                has_connectivity = True
                connected.update(serials)
    residue_sizes = Counter(residue for _, residue in atoms)
    complete = has_connectivity and all(
        serial in connected or residue_sizes[residue] == 1 for serial, residue in atoms
    )
    provenance = path.with_suffix(path.suffix + ".provenance.json")
    # Every receptor in the paper was converted from PDBQT by OpenBabel, so its
    # header alone identifies the same authoritative connectivity; the sidecar is
    # not needed and user-converted files are parsed like the paper's.
    converted = openbabel_output and has_connectivity
    if not converted and provenance.is_file():
        try:
            record = json.loads(provenance.read_text())
            converted = (
                record.get("schema") == "chelate-receptor-pdb-v1"
                and record.get("pdb_sha256")
                == hashlib.sha256(path.read_bytes()).hexdigest()
            )
        except (OSError, ValueError, TypeError):
            pass
    molecule = Chem.MolFromPDBFile(
        str(path), proximityBonding=not (complete or converted)
    )
    if molecule is not None:
        return molecule
    # A partly connected converted PDB can still be valid when proximity bonds
    # are disabled. Never repair its coordinates or remove receptor atoms.
    explicit = Chem.MolFromPDBFile(
        str(path), sanitize=False, removeHs=False, proximityBonding=False
    )
    if explicit is None or not explicit.GetNumBonds():
        return None
    problems = Chem.DetectChemistryProblems(explicit)
    if problems:
        _repair_standard_residue_bond_orders(explicit, problems)
    try:
        Chem.SanitizeMol(explicit)
        explicit = Chem.RemoveHs(explicit)
    except (ValueError, RuntimeError):
        return None
    warnings.warn(
        "Receptor parsing recovered using its explicit connectivity and "
        "standard amino-acid bond orders; coordinates and atoms were preserved.",
        stacklevel=2,
    )
    return explicit


@cache
def _standard_residue_bond_orders() -> dict:
    """Derive named heavy-atom bond orders from RDKit's amino-acid templates."""
    templates = {}
    for code in "ARNDCEQGHILKMFPSTWYV":
        molecule = Chem.MolFromFASTA(code)
        Chem.Kekulize(molecule, clearAromaticFlags=True)
        residue = molecule.GetAtomWithIdx(0).GetPDBResidueInfo().GetResidueName()
        templates[residue] = {
            frozenset(
                molecule.GetAtomWithIdx(index).GetPDBResidueInfo().GetName().strip()
                for index in (bond.GetBeginAtomIdx(), bond.GetEndAtomIdx())
            ): bond.GetBondType()
            for bond in molecule.GetBonds()
        }
    return templates


def _repair_standard_residue_bond_orders(molecule, problems) -> None:
    """Correct conversion bond-order defects only in a failing standard residue.

    For example, OpenBabel may write both CG=CD and CD=OE1 for glutamate.
    Standard residue names and atom names define CG-CD as a single bond. No
    bond is added or removed, and cross-residue links and protonation charges
    are preserved. Unknown residues are left untouched and must still sanitise.
    """
    templates = _standard_residue_bond_orders()
    affected = set()
    for problem in problems:
        if not hasattr(problem, "GetAtomIdx"):
            continue
        info = molecule.GetAtomWithIdx(problem.GetAtomIdx()).GetPDBResidueInfo()
        if info is not None and info.GetResidueName() in templates:
            affected.add(
                (
                    info.GetChainId(),
                    info.GetResidueNumber(),
                    info.GetInsertionCode(),
                    info.GetResidueName(),
                )
            )
    for bond in molecule.GetBonds():
        left = bond.GetBeginAtom().GetPDBResidueInfo()
        right = bond.GetEndAtom().GetPDBResidueInfo()
        if left is None or right is None:
            continue

        def identity(info):
            return (
                info.GetChainId(),
                info.GetResidueNumber(),
                info.GetInsertionCode(),
                info.GetResidueName(),
            )

        if identity(left) not in affected or identity(left) != identity(right):
            continue
        expected = templates[left.GetResidueName()].get(
            frozenset([left.GetName().strip(), right.GetName().strip()])
        )
        if expected is not None:
            bond.SetBondType(expected)
